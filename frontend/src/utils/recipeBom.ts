const normalizeName = (s: string) =>
  s
    .toLowerCase()
    .replace(/cheesy|cheezy/g, 'cheesy')
    .replace(/tandoori/g, 'tandori')
    .replace(/margherita/g, 'marghrita')
    .replace(/chutney/g, 'chuntey')
    .replace(/bread/g, 'bred')
    .replace(/[^a-z0-9\s]/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();

export function findMatchingRecipe(
  itemName: string,
  bomItems: RecipeBomItem[]
): RecipeBomItem | null {
  if (!itemName || !bomItems.length) return null;
  const low = itemName.toLowerCase().trim();

  const exact = bomItems.find((b) => b.name.toLowerCase().trim() === low);
  if (exact) return exact;

  const aliases = ITEM_RECIPE_ALIASES[low];
  if (aliases) {
    for (const alias of aliases) {
      const hit = bomItems.find((b) => b.name.toLowerCase().trim() === alias.toLowerCase());
      if (hit) return hit;
    }
  }

  const normQuery = normalizeName(itemName);
  const queryTokens = normQuery.split(' ').filter((t) => t.length > 1);
  let best: RecipeBomItem | null = null;
  let bestScore = 0;

  for (const item of bomItems) {
    const normTarget = normalizeName(item.name);
    if (normTarget === normQuery) return item;
    if (normTarget.includes(normQuery) || normQuery.includes(normTarget)) {
      return item;
    }
    const targetTokens = new Set(normTarget.split(' ').filter((t) => t.length > 1));
    let overlap = 0;
    for (const tok of queryTokens) {
      if (targetTokens.has(tok)) overlap += 1;
    }
    const score = queryTokens.length > 0 ? overlap / Math.max(queryTokens.length, targetTokens.size) : 0;
    if (score > bestScore && overlap >= 1) {
      bestScore = score;
      best = item;
    }
  }

  return bestScore >= 0.4 ? best : null;
}
